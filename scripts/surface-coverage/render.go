package main

import (
	"fmt"
	"io"
	"sort"
	"strings"
)

// renderMarkdown writes the report for a pull request body: the numbers
// first, then what needs a decision, then the full lists folded away.
func renderMarkdown(w io.Writer, r *Report) {
	name := r.Repo[strings.LastIndex(r.Repo, "/")+1:]
	at := ""
	if r.Commit != "" {
		at = " at `" + r.Commit + "`"
	}
	fmt.Fprintf(w, "### SDK operation coverage: %s%s against SDK %s\n\n", name, at, r.SDK)

	covered := len(r.Covered)
	fmt.Fprintf(w, "| | |\n|---|---:|\n")
	fmt.Fprintf(w, "| SDK %s operations | %d |\n", r.SDK, r.Operations)
	fmt.Fprintf(w, "| Reached by %s | %d (%s) |\n", name, covered, pct(covered, r.Operations))
	fmt.Fprintf(w, "| Not reached | %d |\n", len(r.Uncovered))
	if d := r.Delta; d != nil {
		fmt.Fprintf(w, "| New since %s | %d, %d not reached |\n", d.Previous, len(d.Added), len(d.NewlyUncovered))
		if len(d.Removed) > 0 {
			fmt.Fprintf(w, "| Removed since %s | %d |\n", d.Previous, len(d.Removed))
		}
		if len(d.LostCoverage) > 0 {
			fmt.Fprintf(w, "| Reached through %s, not through %s | %d |\n", d.Previous, r.SDK, len(d.LostCoverage))
		}
	}
	fmt.Fprintf(w, "| Stale references to the SDK | %d |\n\n", len(r.Stale))

	if d := r.Delta; d != nil && len(d.NewlyUncovered) > 0 {
		fmt.Fprintf(w, "**New in %s and not reached by %s:**\n\n", r.SDK, name)
		writeOps(w, d.NewlyUncovered)
		fmt.Fprintln(w)
	}
	if d := r.Delta; d != nil && len(d.LostCoverage) > 0 {
		fmt.Fprintf(w, "**Reached through %s but not through %s:**\n\n", d.Previous, r.SDK)
		writeOps(w, d.LostCoverage)
		fmt.Fprintln(w)
	}
	if len(r.Stale) > 0 {
		fmt.Fprintf(w, "**Stale references** — %s calls SDK surface that %s does not have:\n\n", name, r.SDK)
		for _, s := range r.Stale {
			fmt.Fprintf(w, "- `%s`: %s", s.Symbol, s.Reason)
			if len(s.Operations) > 0 {
				fmt.Fprintf(w, " (performed %s)", codeList(s.Operations))
			}
			fmt.Fprintf(w, "; %s\n", sites(s.Sites))
		}
		fmt.Fprintln(w)
	}
	if len(r.Missing) > 0 {
		fmt.Fprintf(w, "**Calls that do not compile against the pinned SDK** (%d):\n\n", len(r.Missing))
		for _, m := range r.Missing {
			fmt.Fprintf(w, "- `%s:%d`: %s\n", m.File, m.Line, m.Text)
		}
		fmt.Fprintln(w)
	}

	if len(r.Uncovered) > 0 {
		fmt.Fprintf(w, "<details><summary>All %d operations %s does not reach, by area</summary>\n\n", len(r.Uncovered), name)
		fmt.Fprintf(w, "| Area | Operations |\n|---|---|\n")
		for _, g := range byTag(r.Uncovered) {
			fmt.Fprintf(w, "| %s | %s |\n", g.tag, codeList(g.ids))
		}
		fmt.Fprintf(w, "\n</details>\n\n")
	}
	if len(r.RawCalls) > 0 {
		fmt.Fprintf(w, "<details><summary>%d raw HTTP calls not matched to an operation</summary>\n\n", len(r.RawCalls))
		for _, c := range r.RawCalls {
			p := c.Path
			if p == "" {
				p = "(path computed at run time)"
			}
			fmt.Fprintf(w, "- `%s %s` at `%s:%d`\n", c.Method, p, c.Site.File, c.Site.Line)
		}
		fmt.Fprintf(w, "\n</details>\n\n")
	}

	fmt.Fprintf(w, "<sub>Reached means a call site in %s's shipped packages (%s, %d packages, tests excluded) leads to the operation through the SDK %s call graph, or names its path in a raw HTTP call.", name, strings.Join(r.Patterns, " "), r.Packages, r.SDK)
	if r.PinnedSDK != "" && r.PinnedSDK != r.SDK {
		fmt.Fprintf(w, " The code is pinned to SDK %s.", r.PinnedSDK)
	}
	if r.TypeErrors > 0 {
		fmt.Fprintf(w, " %s in its packages: call sites in code that does not compile may be missing.", plural(r.TypeErrors, "type error"))
	}
	dynamic := 0
	for _, c := range r.RawCalls {
		if c.Path == "" {
			dynamic++
		}
	}
	if dynamic > 0 {
		fmt.Fprintf(w, " %s with a path computed at run time may reach operations counted here as not reached.", plural(dynamic, "raw HTTP call"))
	}
	fmt.Fprintf(w, " Generated by basecamp-sdk's `scripts/surface-coverage`.</sub>\n")
}

type tagGroup struct {
	tag string
	ids []string
}

func byTag(ops []Operation) []tagGroup {
	m := map[string][]string{}
	for _, op := range ops {
		m[op.Tag] = append(m[op.Tag], op.ID)
	}
	var out []tagGroup
	for tag, ids := range m {
		sort.Strings(ids)
		out = append(out, tagGroup{tag, ids})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].tag < out[j].tag })
	return out
}

func writeOps(w io.Writer, ops []Operation) {
	for _, op := range ops {
		fmt.Fprintf(w, "- `%s` (%s): `%s %s`\n", op.ID, op.Tag, op.Method, op.Path)
	}
}

func codeList(ids []string) string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = "`" + id + "`"
	}
	return strings.Join(out, ", ")
}

func sites(ss []site) string {
	var parts []string
	for i, s := range ss {
		if i == 3 {
			parts = append(parts, fmt.Sprintf("and %d more", len(ss)-3))
			break
		}
		parts = append(parts, fmt.Sprintf("`%s:%d`", s.File, s.Line))
	}
	return strings.Join(parts, ", ")
}

func plural(n int, noun string) string {
	if n == 1 {
		return "1 " + noun
	}
	return fmt.Sprintf("%d %ss", n, noun)
}

func pct(n, d int) string {
	if d == 0 {
		return "0%"
	}
	return fmt.Sprintf("%.0f%%", 100*float64(n)/float64(d))
}
